"""Core HNL sensitivity engine.

Geometry ray-casting through the GRENDEL mesh, FairShip decay-template loading,
deterministic per-point seeding, hit-event sampling, and the per-(flavor, mass)
acceptance Monte Carlo (:func:`process_mass_point`). Imported both by the
``run_sensitivity`` CLI driver and by the band scripts (``bc_nuisance``,
``channel_breakdown``, ``decay_model_band``), so the shared machinery lives here
rather than inside the driver module.
"""

